/** Migração única, conservadora: SQLite -> PostgreSQL, sem alterar o banco de origem. */
import fs from 'node:fs';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import pg from 'pg';

const quote = name => '"'+String(name).replaceAll('"','""')+'"';
const SAFE_TABLE = /^[a-z][a-z_0-9]*$/i;
const root = path.resolve(import.meta.dirname,'..');
if(fs.existsSync(path.join(root,'.env'))) process.loadEnvFile(path.join(root,'.env'));
const src = path.resolve(root,process.env.SQLITE_SOURCE_PATH||process.env.RETRO_DB_PATH||'data/retro-play.sqlite');
const url = process.env.DATABASE_URL;
if(process.env.CONFIRM_MIGRATION!=='YES') throw new Error('Migração não iniciada. Defina CONFIRM_MIGRATION=YES após efetuar backup.');
if(!url)throw new Error('Defina DATABASE_URL para o PostgreSQL de destino.');
if(!fs.existsSync(src))throw new Error('SQLite de origem não encontrado: '+src);
const sqlite=new DatabaseSync(src,{readOnly:true});
const client = new pg.Client({connectionString:url,ssl:process.env.PGSSL==='require'?{rejectUnauthorized:true}:undefined});

function tables(){return sqlite.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map(x=>x.name);}
function columns(t){return sqlite.prepare(`PRAGMA table_info(${quote(t)})`).all();}
function foreignKeys(t){return sqlite.prepare(`PRAGMA foreign_key_list(${quote(t)})`).all();}
function indexes(t){return sqlite.prepare(`PRAGMA index_list(${quote(t)})`).all();}
function indexCols(index){return sqlite.prepare(`PRAGMA index_info(${quote(index)})`).all().map(c=>c.name);}
function pgType(type){const t=String(type).toUpperCase();if(/INT/.test(t))return 'BIGINT';if(/REAL|FLOA|DOUB/.test(t))return 'DOUBLE PRECISION';if(/BLOB/.test(t))return 'BYTEA';return 'TEXT';}
function idName(table){return 'retro_'+table+'_id_pk';}
function createDDL(t){
 const cs=columns(t),pk=cs.filter(x=>x.pk).sort((a,b)=>a.pk-b.pk);
 const lines=cs.map(c=>`${quote(c.name)} ${pgType(c.type)}${c.notnull?' NOT NULL':''}${c.dflt_value!=null?' DEFAULT '+c.dflt_value:''}`);
 if(pk.length===1 && pk[0].type.toUpperCase()==='INTEGER'){
   const i=cs.findIndex(x=>x.name===pk[0].name);lines[i]=`${quote(pk[0].name)} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
 } else if(pk.length){lines.push(`PRIMARY KEY (${pk.map(c=>quote(c.name)).join(', ')})`);}
 return `CREATE TABLE ${quote(t)} (\n  ${lines.join(',\n  ')}\n)`;
}
async function main(){
 const ts=tables();if(!ts.includes('users')||!ts.includes('movies'))throw new Error('O SQLite não parece conter o esquema esperado do Retro Play.');
 const integrity=sqlite.prepare('PRAGMA integrity_check').get();if(Object.values(integrity)[0]!=='ok')throw new Error('Falha na integridade do SQLite.');
 await client.connect();
 try{
  await client.query('BEGIN');
  // Impede importar por cima de outra instalação ou uma importação anterior.
  const existing=await client.query(`SELECT table_name FROM information_schema.tables WHERE table_schema=current_schema() AND table_type='BASE TABLE'`);
  if(existing.rowCount)throw new Error('O schema PostgreSQL de destino já contém tabelas. Use um banco/schema novo e vazio.');
  await client.query('SET LOCAL lock_timeout = \'10s\'');
  let total=0;
  for(const t of ts){
   if(!SAFE_TABLE.test(t))throw new Error('Nome inesperado de tabela: '+t);
   await client.query(createDDL(t));
  }
  for(const t of ts){
   const cs=columns(t);const names=cs.map(c=>c.name),qnames=names.map(quote).join(',');
   const rows=sqlite.prepare(`SELECT ${qnames} FROM ${quote(t)}`).all();
   // Bateladas evitam atingir o limite de parâmetros do PostgreSQL.
   for(let offset=0;offset<rows.length;offset+=100){
    const batch=rows.slice(offset,offset+100),params=[],placeholders=[];
    for(const row of batch){
      const vals=names.map(n=>row[n]);
      params.push(...vals);
      placeholders.push('('+names.map((_,i)=>'$'+(params.length-names.length+i+1)).join(',')+')');
    }
    await client.query(`INSERT INTO ${quote(t)} (${qnames}) VALUES ${placeholders.join(',')}`,params);
   }
   total+=rows.length;
   const id=cs.find(c=>c.name==='id'&&c.pk===1&&c.type.toUpperCase()==='INTEGER');
   if(id){await client.query(`SELECT setval(pg_get_serial_sequence($1,'id'), COALESCE((SELECT MAX(id) FROM ${quote(t)}),1), (SELECT COUNT(*)>0 FROM ${quote(t)}))`,[t]);}
   console.log(`${t}: ${rows.length} registro(s)`);
  }
  // Índices UNIQUE devem ser preservados, inclusive pares compostos.
  for(const t of ts){
    for(const idx of indexes(t)){
      const cols=indexCols(idx.name);if(!cols.length)continue;
      if(idx.origin==='pk')continue;
      const label=`rp_${t}_${cols.join('_')}_${idx.unique?'uq':'idx'}`.slice(0,58);
      await client.query(`CREATE ${idx.unique?'UNIQUE ':''}INDEX ${quote(label)} ON ${quote(t)} (${cols.map(quote).join(',')})`);
    }
  }
  // FKs são adicionadas após carregar os registros; assim ciclos/referências futuras não impedem a importação.
  for(const t of ts){
    const groups=new Map();for(const fk of foreignKeys(t)){
     if(!groups.has(fk.id))groups.set(fk.id,[]);groups.get(fk.id).push(fk);
    }
    for(const [id,group] of groups){
      group.sort((a,b)=>a.seq-b.seq);
      const to=group[0].table;
      if(!ts.includes(to))throw new Error(`FK inesperada ${t} -> ${to}`);
      const action=group[0].on_delete==='CASCADE'?' ON DELETE CASCADE':group[0].on_delete==='SET NULL'?' ON DELETE SET NULL':'';
      await client.query(`ALTER TABLE ${quote(t)} ADD CONSTRAINT ${quote('rp_fk_'+t+'_'+id)} FOREIGN KEY (${group.map(x=>quote(x.from)).join(',')}) REFERENCES ${quote(to)} (${group.map(x=>quote(x.to)).join(',')})${action}`);
    }
  }
  // Constraints críticas preservadas para não aceitar entradas inválidas.
  await client.query(`ALTER TABLE users ADD CONSTRAINT rp_users_role CHECK (role IN ('user','admin'))`);
  await client.query(`ALTER TABLE movies ADD CONSTRAINT rp_movies_access CHECK (access_type IN ('free','subscription','rental','both'))`);
  await client.query(`ALTER TABLE payments ADD CONSTRAINT rp_payments_kind CHECK (kind IN ('rental','subscription'))`);
  await client.query(`ALTER TABLE reviews ADD CONSTRAINT rp_reviews_stars CHECK (stars BETWEEN 1 AND 5)`);
  for(const t of ts){
    const expected=sqlite.prepare(`SELECT count(*) AS n FROM ${quote(t)}`).get().n;
    const actual=Number((await client.query(`SELECT count(*) AS n FROM ${quote(t)}`)).rows[0].n);
    if(expected!==actual)throw new Error(`Contagem divergente em ${t}: SQLite=${expected}, PostgreSQL=${actual}`);
  }
  await client.query('COMMIT');
  console.log(`MIGRAÇÃO CONCLUÍDA: ${total} registro(s), ${ts.length} tabelas. SQLite de origem intacto.`);
  console.log('ATENÇÃO: o servidor do Retro Play ainda usa SQLite; migrar dados não troca o backend automaticamente.');
 }catch(e){await client.query('ROLLBACK');throw e;}finally{await client.end();sqlite.close();}
}
main().catch(e=>{console.error('MIGRAÇÃO CANCELADA:',e.message);process.exitCode=1;});
